"""Вывод в консоль. Отдельный модуль, чтобы при желании заменить print на logging в одном месте."""


def log(text=""):
    """Печатает одну строку лога."""
    print(text)


def stage(number, title):
    """Печатает заголовок этапа, например «Этап 5. Prefill …», с рамкой из линий.

    number — номер этапа из урока 02 (или строка вроде «Т1» для этапов обучения).
    """
    log(f"\n{'═' * 72}\nЭтап {number}. {title}\n{'═' * 72}")
