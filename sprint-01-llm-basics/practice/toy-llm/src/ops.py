"""Операции над векторами и матрицами — «кирпичики», из которых собран трансформер.

Вектор здесь — list[Value], матрица — list[list[Value]].
"""
import math

from .autograd import dot, vsum


def linear(x, W):
    """Умножает вектор на матрицу-преобразование (урок 01, раздел 2).

    W хранится по столбцам: W[j] — столбец, описывающий, как из всех входных чисел
    посчитать j-е выходное число (взвешенная сумма входов). Матрица из 64 столбцов
    по 16 чисел принимает вектор из 16 чисел и выдаёт вектор из 64.
    """
    return [dot(x, column) for column in W]


def add(a, b):
    """Поэлементная сумма двух векторов. Так реализована остаточная связь (урок 01, 4.4)."""
    return [x + y for x, y in zip(a, b)]


def rmsnorm(x):
    """Нормализация вектора (урок 01, 4.4): делит его на среднеквадратичное значение чисел.

    После неё числа вектора в среднем порядка единицы, и они не разрастаются
    и не затухают, проходя через десятки слоёв. Вариант RMSNorm используют
    современные модели (Llama, Qwen, gpt-oss).
    """
    mean_square = vsum([v * v for v in x]) * (1.0 / len(x))
    scale = (mean_square + 1e-5) ** -0.5
    return [v * scale for v in x]


def softmax(logits):
    """Превращает логиты (список Value) в вероятности (урок 01, 4.7).

    Каждое число переводится в e^x и делится на сумму всех e^x: всё становится
    от 0 до 1, сумма равна 1, и большее исходное число даёт большую вероятность.
    Максимум вычитаем заранее, чтобы e^x не переполнился; на результат это не влияет.
    """
    top = max(v.data for v in logits)
    exps = [(v - top).exp() for v in logits]
    total = vsum(exps)
    return [e / total for e in exps]


def softmax_floats(xs):
    """Тот же softmax, но для обычных чисел. Нужен движку при выборе токена: градиенты там не нужны."""
    top = max(xs)
    exps = [math.exp(x - top) for x in xs]
    total = sum(exps)
    return [e / total for e in exps]


def rope(vec, pos):
    """RoPE (урок 01, 4.3): поворачивает пары чисел вектора на угол «позиция × частота».

    Пары (0,1), (2,3), … — точки на плоскости. У первых пар частота высокая (крутятся
    быстро), у последних низкая, как стрелки часов. Применяется к запросу и ключу перед
    их сравнением во внимании, и тогда результат сравнения зависит от расстояния
    между токенами, а не от их абсолютных позиций.

    vec — вектор одной головы внимания (чётной размерности), pos — позиция токена.
    """
    out = []
    dim = len(vec)
    for i in range(0, dim, 2):
        freq = 10000 ** (-i / dim)
        angle = pos * freq
        c, s = math.cos(angle), math.sin(angle)
        a, b = vec[i], vec[i + 1]
        out += [a * c - b * s, a * s + b * c]
    return out
